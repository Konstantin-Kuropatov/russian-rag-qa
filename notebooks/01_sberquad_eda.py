# спецтокены требуют дополнительного бюджета. Сравнивать эти режимы как одинаковый
# бюджет нельзя. Проверяется только геометрическое попадание целого gold span
# хотя бы в одно окно, а не то, сможет ли модель найти окно или извлечь ответ.

