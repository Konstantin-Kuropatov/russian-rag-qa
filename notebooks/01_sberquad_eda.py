# выводы о качестве делать нельзя. Нахождение gold passage не означает,
# что RAG сформировал правильный и полный ответ.

# %% [markdown]
# ## 14. Что принимаем для следующих этапов
#
# | Наблюдение | Решение |
# | --- | --- |
# | Исходный test без опубликованных ответов | Не считать его no-answer; для end-to-end оценки использовать внутренний размеченный test. |
# | Validation содержит виденные контексты | Хранить исходный протокол и дополнительно использовать подготовленный групповой split. |
# | Повторы корпуса под разными ID | Индексировать канонические тексты, преобразовывать qrels и сохранять provenance. |
# | Неправильные offsets и вхождения внутри слов | Начать reader с `reader_eligible`; остальные spans не удалять и не исправлять смысл автоматически. |
# | Только положительные qrels | Отрицательные примеры собирать явно, проверять риск false negatives. |
# | Вопросы иногда нуждаются в контексте | Использовать отдельную оценочную группу и качественный разбор. |
# | Короткий единственный эталон | Сочетать EM/token-F1 с проверкой подтверждённости и небольшой ручной оценкой. |
# | Небольшая часть длинных абзацев | Проверить окна и overlap, сохраняя связь с исходным фрагментом. |
# | Лексическая близость влияет на диагностический поиск | Сравнить BM25, dense и hybrid на одинаковых корпусе и split. |
#
# **Практическая применимость.** Датасет подходит для контролируемого поиска и
# коротких фактологических ответов на русском языке. По нему нельзя подтвердить
# качество на корпоративных документах, актуальность знаний, многошаговые ответы,
# безопасность или надёжность отказа при отсутствии сведений. Для реального
# ассистента понадобятся доменные документы и независимо собранные вопросы.
# Открытые Wikipedia-вопросы также могут быть знакомы предобученной LLM;
# в дальнейшем нужен контроль ответа без retrieval и с неподходящим контекстом.

